/**
 * @module cameraLimitConfig.ts Конфигурация ограничений для камеры
 *
 * Параметры для контроля того, на сколько может отдаляться камера
 * когда змейка растёт
 */

export const cameraLimitCONFIG = {
  /**
   * Максимальное увеличение расстояния камеры в процентах от начального Z
   *
   * Примеры:
   * - 0.2 = камера может отдаляться максимум на 20% (z = 25 * 1.2 = 30)
   * - 0.3 = камера может отдаляться максимум на 30% (z = 25 * 1.3 = 32.5)
   * - 0.5 = камера может отдаляться максимум на 50% (z = 25 * 1.5 = 37.5)
   *
   * РЕКОМЕНДУЕМЫЕ ЗНАЧЕНИЯ: 0.2 - 0.4
   */
  MAX_ZOOM_OUT_PERCENT: 0.2,

  /**
   * Альтернативное описание - максимальное дополнительное расстояние в абсолютных единицах
   *
   * Если MAX_ZOOM_OUT_PERCENT не подходит, можно использовать абсолютное значение
   * Например: вместо "20% от 25", просто "максимум +5 единиц от начального Z"
   */
  MAX_ADDITIONAL_Z_DISTANCE: null, // null = не используется, используется процент выше
} as const
